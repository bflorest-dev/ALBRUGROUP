CREATE TABLE gestion_reclutamiento (
 postulacion_id BIGINT PRIMARY KEY REFERENCES postulacion(id),
 revision BIGINT NOT NULL DEFAULT 0,
 evaluada_at TIMESTAMP,
 ultima_gestion_at TIMESTAMP,
 ultimo_resultado VARCHAR(80)
);
CREATE TABLE actividad_reclutamiento (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 postulacion_id BIGINT NOT NULL REFERENCES postulacion(id),
 tipo VARCHAR(30) NOT NULL CHECK (tipo IN ('ENTREVISTA','REINTENTO')),
 modalidad VARCHAR(30) NOT NULL CHECK (modalidad IN ('LLAMADA','WHATSAPP','MEET','PRESENCIAL')),
 fecha_hora TIMESTAMP NOT NULL,
 referencia VARCHAR(500),
 estado VARCHAR(30) NOT NULL CHECK (estado IN ('PENDIENTE','REALIZADA','REPROGRAMADA','CANCELADA','INASISTENCIA')),
 responsable_id BIGINT NOT NULL,
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE UNIQUE INDEX actividad_reclutamiento_pendiente ON actividad_reclutamiento(postulacion_id) WHERE estado='PENDIENTE';
CREATE INDEX actividad_reclutamiento_historial ON actividad_reclutamiento(postulacion_id, id DESC);
